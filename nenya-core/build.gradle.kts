// ---------------------------------------------------------------------------------
// Vendored test files for common tests. A common test cannot open a file: on the JVM
// the working directory is the module, on Node it is build/js/packages/<name>-test, and
// JavaScript has no class path. So the files common tests read are compiled INTO the
// test code instead: this task writes one Kotlin source, VendoredTestFiles.kt, holding
// each file's exact text as string constants, keyed by its path from the repository
// root. It runs offline and uses nothing but the JDK.
//
// Faithfulness is not assumed: VendoredTestFilesTest (jvmTest) re-reads every listed
// file from disk and asserts the generated text encodes to the same bytes, and that the
// generated key set is exactly the list below.
//
// SHA256LongMsg.rsp (426 KB) is deliberately NOT listed: the NIST vector tests that read
// it stay in jvmTest and open it from disk.
// ---------------------------------------------------------------------------------
abstract class GenerateVendoredTestFiles : DefaultTask() {

    /** Paths from the repository root; they become the lookup keys, in this order. */
    @get:Input
    abstract val paths: ListProperty<String>

    @get:Internal
    abstract val repositoryRoot: DirectoryProperty

    /** The same files, declared as inputs so an edit to any of them regenerates. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = repositoryRoot.get().asFile
        val keys = paths.get()
        require(keys.isNotEmpty()) { "no vendored test files listed" }
        require(keys.toSet().size == keys.size) { "a vendored test file is listed twice: $keys" }
        val out = StringBuilder()
        out.append("// GENERATED by :nenya-core:generateVendoredTestFiles from the files listed in\n")
        out.append("// nenya-core/build.gradle.kts. Do not edit: edit the source file and rebuild.\n")
        out.append("package dev.eryalabs.nenya\n\n")
        out.append("/** The vendored test files, compiled in as text. Keys are paths from the repository root. */\n")
        out.append("internal object VendoredTestFiles {\n\n")
        out.append("    val paths: List<String> = listOf(\n")
        for (key in keys) out.append("        ").append(literal(key)).append(",\n")
        out.append("    )\n\n")
        out.append("    fun text(path: String): String = when (path) {\n")
        keys.forEachIndexed { index, key -> out.append("        ").append(literal(key)).append(" -> file$index\n") }
        out.append("        else -> throw IllegalArgumentException(\"no vendored test file is generated for '\" + path + \"'; generated: \" + paths)\n")
        out.append("    }\n")
        keys.forEachIndexed { index, key ->
            val file = root.resolve(key)
            require(file.isFile) { "vendored test file $key is not at ${file.absolutePath}" }
            val raw = file.readBytes()
            val text = try {
                Charsets.UTF_8.newDecoder()
                    .onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT)
                    .decode(ByteBuffer.wrap(raw))
                    .toString()
            } catch (e: CharacterCodingException) {
                throw GradleException("vendored test file $key is not valid UTF-8", e)
            }
            out.append("\n    /** ").append(key.replace("*/", "*\\/")).append(", ").append(raw.size).append(" bytes. */\n")
            out.append("    private val file$index: String by lazy {\n")
            out.append("        buildString(").append(text.length).append(") {\n")
            var start = 0
            while (start < text.length) {
                var end = minOf(start + CHUNK, text.length)
                // Never split a surrogate pair across two literals.
                if (end < text.length && text[end - 1].isHighSurrogate()) end--
                out.append("            append(").append(literal(text.substring(start, end))).append(")\n")
                start = end
            }
            out.append("        }\n")
            out.append("    }\n")
        }
        out.append("}\n")
        val target = outputDirectory.get().asFile.resolve("dev/eryalabs/nenya/VendoredTestFiles.kt")
        target.parentFile.mkdirs()
        target.writeText(out.toString(), Charsets.UTF_8)
    }

    private companion object {
        /** Characters per literal: far below the JVM's 65535-byte constant-pool string limit. */
        const val CHUNK: Int = 8000

        /** A Kotlin string literal: only printable ASCII is written raw, everything else as \uXXXX. */
        fun literal(value: String): String {
            val sb = StringBuilder(value.length + 2).append('"')
            for (c in value) {
                when {
                    c == '\\' || c == '"' || c == '$' -> sb.append('\\').append(c)
                    c.code < 0x20 || c.code > 0x7e -> sb.append("\\u").append(c.code.toString(16).padStart(4, '0'))
                    else -> sb.append(c)
                }
            }
            return sb.append('"').toString()
        }
    }
}

