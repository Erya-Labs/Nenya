val generateVendoredTestFiles = tasks.register<GenerateVendoredTestFiles>("generateVendoredTestFiles") {
    description = "Compiles the vendored spec and vector files into a Kotlin source for commonTest."
    paths.set(vendoredTestFilePaths)
    repositoryRoot.set(rootProject.layout.projectDirectory)
    sources.from(vendoredTestFilePaths.map { rootProject.file(it) })
    outputDirectory.set(layout.buildDirectory.dir("generated/vendoredTestFiles/commonTest/kotlin"))
}

kotlin {
    // The published surface is a contract for third-party clients. Explicit API
    // mode forces every public declaration to carry an explicit visibility and
    // return type, so nothing leaks into the ABI by accident. Applies to every target.
    explicitApi()
    jvmToolchain(17)

    // Code that is truly common lives in src/commonMain / src/commonTest and compiles
    // for both targets; everything still JVM-bound lives in src/jvmMain / src/jvmTest.
    jvm()

    // Node only, no browser(): browser tests would need a headless Chrome. Compiling
    // (compileKotlinJs, compileTestKotlinJs) needs no Node, Yarn or npm; running JS tests
    // (jsNodeTest, jsTest, allTests, check, build) and assemble do, and are not loop gates.
    js(IR) {
        moduleName = "nenya"
        nodejs {
            testTask {
                useMocha {
                    // Mocha's default per-test limit is 2000 ms, and it fails a synchronous
                    // test that finishes after that limit even when every assertion passed.
                    // The seeded property tests (BidPropertyTest, ListingPropertyTest,
                    // TagPropertyTest) each build and round-trip a whole generated corpus and
                    // took 2.2-3.0 s on Node 22 on the first JS run, so 7 of them "failed"
                    // on time alone. 30 s is a hang detector, not a performance budget.
                    timeout = "30s"
                }
            }
        }
        binaries.library()
        generateTypeScriptDefinitions()
        useEsModules()
    }

    sourceSets {
        commonTest {
            // The vendored spec and vector files, as Kotlin string constants (see
            // GenerateVendoredTestFiles above). Passing the task provider makes every
            // compilation of commonTest depend on the generator.
            kotlin.srcDir(generateVendoredTestFiles)
        }
        commonTest.dependencies {
            implementation(libs.kotlin.test)
        }
        jvmTest.dependencies {
            implementation(libs.junit)
            implementation(libs.kotlin.test.junit)
        }
    }
}

// srcDir(taskProvider) already carries the dependency; stated explicitly for the two
