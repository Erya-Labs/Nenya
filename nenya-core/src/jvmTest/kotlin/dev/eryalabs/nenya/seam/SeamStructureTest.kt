        assertNull(stringParameterIn(probe.methods.single { it.name == "permitted" }))
        assertNull(stringParameterIn(probe.methods.single { it.name == "neighbour" }))
    }

    /**
     * A probe, not a fixture. `neighbour` is the one that earns [namesType]: `java.lang.StringBuilder`
     * contains `java.lang.String`, and a sweep built on `contains` would report it.
     */
    @Suppress("unused")
    private class StringCollectionProbe {
        fun wrapped(events: List<String>): Int = events.size
        fun keyed(events: Map<String, Int>): Int = events.size
        fun nested(events: List<List<String>>): Int = events.size
        fun direct(event: String): Int = event.length
        fun permitted(counts: List<Int>): Int = counts.size
        fun neighbour(builder: StringBuilder): Int = builder.length
    }

