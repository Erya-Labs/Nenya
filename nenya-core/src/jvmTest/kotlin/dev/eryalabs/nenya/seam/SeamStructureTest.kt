        /** Constructors and own public methods, minus everything a client cannot name. */
        fun publishedExecutables(type: Class<*>): List<java.lang.reflect.Executable> =
            type.constructors.toList() + SeamReflection.publishedMethods(type)

        /**
         * Every type [executable] **accepts**, printed in its parameterised form.
         *
         * `getParameterTypes()` is the **erasure**, so a published `fun x(flags: List<Boolean>)`
         * reports `List` and satisfies every parameter rule in this file while handing a caller
         * exactly the shape those rules forbid. `getGenericParameterTypes()` prints
         * `java.util.List<java.lang.Boolean>`, which is what the sweeps below match on.
         *
         * Return types are deliberately not folded in here: each rule that uses this one is about
         * what the surface *accepts*, and [returnedTypes] is the sweep for the other direction.
         */
        fun acceptedTypeNames(executable: java.lang.reflect.Executable): List<String> =
            executable.genericParameterTypes.map { it.typeName }

        /**
         * Whether [typeName] names [sought] itself, or names it inside a generic's type arguments.
         *
         * A bare `contains` is wrong: `java.lang.StringBuilder` contains `java.lang.String`, and a
         * sweep that reported it would be one nobody keeps. So the match is on a whole type token —
         * the character either side must not continue an identifier. Plain string operations rather
         * than a pattern: a pattern is a second grammar to get right in a file whose whole subject
         * is checks that quietly match nothing.
         */
        fun namesType(typeName: String, sought: String): Boolean {
            var from = 0
            while (true) {
                val at = typeName.indexOf(sought, from)
                if (at < 0) return false
                val before = if (at == 0) ' ' else typeName[at - 1]
                val afterAt = at + sought.length
                val after = if (afterAt >= typeName.length) ' ' else typeName[afterAt]
                if (!continuesIdentifier(before) && !continuesIdentifier(after)) return true
                from = at + 1
            }
        }

        private fun continuesIdentifier(character: Char): Boolean =
            character.isLetterOrDigit() || character == '.' || character == '$' || character == '_'

        /**
         * The first type [executable] accepts that names a `Boolean`, or `null` if none does.
         *
         * Both spellings, and the pair is the whole point: a bare Kotlin `Boolean` parameter erases
         * to the JVM primitive, whose `typeName` is `boolean`, while the same type inside a generic
         * is boxed and reads `java.lang.Boolean`. Checking one of the two would leave
         * `List<Boolean>` exactly as invisible as the erased check this replaced.
         */
        fun booleanParameterIn(executable: java.lang.reflect.Executable): String? =
            acceptedTypeNames(executable).firstOrNull {
                namesType(it, "boolean") || namesType(it, "java.lang.Boolean")
            }

        /** The first type [executable] accepts that names a `String`, or `null` if none does. */
        fun stringParameterIn(executable: java.lang.reflect.Executable): String? =
            acceptedTypeNames(executable).firstOrNull { namesType(it, "java.lang.String") }

        /**
         * The first type [executable] accepts that names a `ByteArray`, or `null` if none does.
         *
         * `byte[]` and not `ByteArray`, because `typeName` prints the JVM's spelling for an array.
         * It is also why every expected side in this file is built from `::class.java.typeName` and
         * never from `.name`: the latter is `[B`, which matches no parameterised type at all.
         */
        fun byteArrayParameterIn(executable: java.lang.reflect.Executable): String? =
            acceptedTypeNames(executable).firstOrNull { namesType(it, "byte[]") }

        /**
         * Every class a member's return type mentions, including the arguments of a generic.
         *
         * `getReturnType()` is the **erasure**, so a `Wallet.mintOrderId(): SeamAnswer<OrderId>`
         * returns `SeamAnswer` and is invisible to a sweep that reads it. Since every seam method
         * returns `SeamAnswer<T>` by design, that one wrapper is precisely the shape that would
         * defeat these checks — so they walk the type arguments too.
         */
        fun returnedTypes(executable: java.lang.reflect.Executable): List<Class<*>> {
            val method = executable as? Method ?: return emptyList()
            val out = mutableListOf<Class<*>>(method.returnType)
            fun walk(type: java.lang.reflect.Type) {
                when (type) {
                    is Class<*> -> out += type
                    is ParameterizedType -> {
                        (type.rawType as? Class<*>)?.let { out += it }
                        type.actualTypeArguments.forEach { walk(it) }
                    }
                    is java.lang.reflect.WildcardType -> {
                        type.upperBounds.forEach { walk(it) }
                        type.lowerBounds.forEach { walk(it) }
                    }
                }
            }
            walk(method.genericReturnType)
            return out
        }

        fun syntheticConstructorOfOrderId(): Constructor<*> =
            SeamReflection.byName("OrderId").declaredConstructors
                .single { it.parameterTypes.size == 2 }
                .also { it.isAccessible = true }
    }

    @Test
    fun `the sweep finds the classes it is about, by name`() {
        val found = SeamReflection.mainClasses().map { it.name.removePrefix("${SeamReflection.PACKAGE}.") }

        for (expected in EXPECTED_BY_NAME) {
            assertTrue(
                expected in found,
                "$expected was not among the main classes of ${SeamReflection.PACKAGE}; found $found",
            )
        }
    }

    /**
     * §9.1 as an absence, read through the parameterised type rather than the erasure.
     *
     * This sweep used to read `getParameterTypes()`, which reports `List` for a
     * `fun settle(flags: List<Boolean>)` — so the one rule STOP RULE 12 states most plainly was
     * satisfied by wrapping the lie in a collection. [booleanParameterIn] reads the generic form,
     * and the probe below is what proves it.
     */
    @Test
    fun `no published constructor or method in the seam package accepts a Boolean`() {
        // Its own by-name guard rather than only the `inspected` floor below: a bare member count
        // is satisfied by the test tree alone, so this is the assertion that would stay green if
        // `mainClasses()` started resolving to the wrong output directory.
        val published = SeamReflection.publishedClasses()
        val found = published.map { it.name.removePrefix("${SeamReflection.PACKAGE}.") }.toSet()
        assertTrue(
            EXPECTED_BY_NAME.all { it in found },
            "the Boolean sweep must be looking at $EXPECTED_BY_NAME, not at whatever classpath entry " +
                "it happened to land on; it found $found",
        )

        var inspected = 0
        for (type in published) {
            for (executable in publishedExecutables(type)) {
                inspected++
                val offender = booleanParameterIn(executable)
                assertNull(
                    offender,
                    "${SeamReflection.label(type, executable)} takes a Boolean, as `$offender`. " +
                        "§9.1: a wallet's `isPaid` is not evidence, and a seam that can be *told* " +
                        "the answer is a shorter route to the same lie.",
                )
            }
        }
        assertTrue(inspected > 20, "the sweep inspected only $inspected members, which is not the package")
    }

    /**
     * The control that proves the sweep above is not erasure-blind.
     *
     * Without it, "no published member takes a Boolean" is satisfied by a predicate that never
     * matches a `List<Boolean>` — which is precisely what the erased-type check it replaced was.
     * The probe is fed to [booleanParameterIn], the sweep's **own** predicate: a control that
     * exercised a second copy of the check would prove nothing about the first, which is the exact
     * failure mode this conversion exists to fix.
     */
    @Test
    fun `the Boolean sweep catches a Boolean hidden inside a generic parameter`() {
        val probe = BooleanCollectionProbe::class.java
        for (name in listOf("wrapped", "keyed", "nested")) {
            val method = probe.methods.single { it.name == name }
            assertNotNull(
                booleanParameterIn(method),
                "BooleanCollectionProbe.$name hides a Boolean and the sweep's own predicate missed " +
                    "it — ${acceptedTypeNames(method)} erases past a check that reads the erasure",
            )
        }
        // Caught by the old predicate too: this is what shows the two controls test different things.
        assertNotNull(booleanParameterIn(probe.methods.single { it.name == "direct" }))
        // Not merely "reject every generic".
        assertNull(booleanParameterIn(probe.methods.single { it.name == "permitted" }))
    }

    /**
     * A probe, not a fixture: three shapes that hide the forbidden type, the plain one the erased
     * check already caught, and a generic of a permitted type that must stay uncaught.
     *
     * Declared here and never in `src/jvmMain`, and its members are found by reflection, so a probe
     * that failed to compile into the test output cannot pass vacuously — `single` throws.
     */
    @Suppress("unused")
    private class BooleanCollectionProbe {
        fun wrapped(flags: List<Boolean>): Int = flags.size
        fun keyed(flags: Map<String, Boolean>): Int = flags.size
        fun nested(flags: List<List<Boolean>>): Int = flags.size
        fun direct(flag: Boolean): Int = if (flag) 1 else 0
        fun permitted(names: List<String>): Int = names.size
    }

    /**
     * The pinned list, read through the parameterised type: a `List<String>` is a String parameter.
     *
     * The erased form of this sweep asked only whether a parameter *was* `String`, so a member
     * taking `List<String>` or `Map<String, String>` joined the published surface without a human
     * ever being asked why it is not a status string smuggled in as evidence — which is the entire
     * job of the pin.
     */
    @Test
    fun `every published String parameter is on the pinned list`() {
        val found = mutableSetOf<String>()
        for (type in SeamReflection.publishedClasses()) {
            for (executable in publishedExecutables(type)) {
                if (stringParameterIn(executable) != null) {
                    found += SeamReflection.label(type, executable)
                }
            }
        }

        assertEquals(
            STRING_PARAMETERS_PERMITTED,
            found,
            "the set of published members taking a String must match the pinned list exactly. A new " +
                "entry may be a status string arriving as evidence; a missing entry means the sweep " +
                "stopped seeing the package.",
        )
    }

    /**
     * The control that proves the pin above is not erasure-blind.
     *
     * Fed to [stringParameterIn], the sweep's own predicate. A member taking `List<String>` is a
     * member taking strings, and before the conversion it could join the surface without appearing
     * in [STRING_PARAMETERS_PERMITTED] at all.
     */
    @Test
    fun `the String pin catches a String hidden inside a generic parameter`() {
        val probe = StringCollectionProbe::class.java
        for (name in listOf("wrapped", "keyed", "nested")) {
            val method = probe.methods.single { it.name == name }
            assertNotNull(
                stringParameterIn(method),
                "StringCollectionProbe.$name hides a String and the pin's own predicate missed it — " +
                    "${acceptedTypeNames(method)} erases past a check that reads the erasure",
            )
        }
        // Caught by the old predicate too: this is what shows the two controls test different things.
        assertNotNull(stringParameterIn(probe.methods.single { it.name == "direct" }))
