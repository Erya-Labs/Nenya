/**
 * T42's proof: for each of the thirteen exported entry points, the facade's answer is the answer the
 * underlying library call gives for the same input — over a corpus, including every refusal the
 * corpus reaches.
 *
 * ### What this is for
 *
 * Decision **P** says the JavaScript layer adds no rule and relaxes none, and T42 says the facade
 * performs no check of its own. Those are claims about behaviour, so they are proved by behaviour: for
 * every case two calls are made — one through `dev.eryalabs.nenya.js` and one straight at
 * `ListingWriter` / `RumorWriter` / `PaymentWriter` / `Listing.decode` / `Bid.decode` — and the two
 * answers must agree down to §4.1's canonical object form, which carries the recomputed `id`.
 *
 * A translation layer that re-implemented a check would be the divergence STOP RULE 5 exists to
 * prevent, and it would show here as one side accepting what the other refused.
 *
 * ### Why both sides are not the same code
 *
 * `JsBoundaryFixtures` holds a **second** translation, written from the Kotlin types' published fields
 * rather than borrowed from the facade's own private helpers. See that file's note: feeding the
 * facade's `asAuthoredListing` into `ListingWriter` would have proved the call was made and nothing
 * about the crossing, and the defect this task fixed — §8.1's `Stated(0)` crossing as `Absent`, so a
 * `["fee", "0"]` listing lost the tag and changed its own id — lived in exactly that gap.
 *
 * ### In `commonTest`, so it runs on JavaScript
 *
 * This is the half of the library that exists *for* JavaScript, and the scheduled webtest job runs
 * every common test as JavaScript on each new commit. A JVM-only proof of a JavaScript facade would be
 * the one place a JVM-only test proves least.
 */
class JsFacadeEqualityTest {

    private companion object {

        /**
         * Listing cases, each built through **all three** of §5.1's and §5.2's entry points.
         *
         * Every case through every kind rather than one kind each, and the extra coverage is the
         * refusals: `ListingWriterFixtures` draws a `status` from the vocabulary of the kind it
         * generated for, so re-reading that token under a different kind reaches §5.2's
         * `UNKNOWN_IS_NOT_EMITTABLE` and §5.2's `alt` requirement from both sides. A refusal the two
         * sides must spell identically is as much of this proof as a built event.
         */
        const val LISTING_CASES: Int = 120

        /** §7.4's eight shapes, cycled, so each of the eight writers sees 30 cases. */
        const val RUMOR_CASES: Int = 240

        /** Legal §6 bids, for the `decodeBid` corpus. */
        const val BID_CASES: Int = 90

        /** Built listings serialised and fed back through `decodeListing`. */
        const val DECODE_CASES: Int = 120

        /** One seeded run, shared by the eight per-shape sweeps rather than regenerated by each. */
        val RUMORS: List<RumorWriterFixtures.Case> = RumorWriterFixtures.cases(RUMOR_CASES)

        /** §5.1's and §5.2's three kinds, in the order the sweep walks them. */
        val LISTING_KINDS: List<Int> = listOf(NenyaKind.REQUEST, NenyaKind.OFFER, NenyaKind.OFFER_DRAFT)

        /**
         * [listing] as the same values read for [kind].
         *
         * Only `status` changes, and it has to: §5.1's and §5.2's vocabularies differ, so the token a
         * case carries means a different `ListingStatus` — or none — under another kind. Read through
         * `ListingStatusCodec.read`, which is the call the facade makes for the same token, because
         * the question here is whether the two *crossings* agree and not whether the codec is right.
         */
        fun asKind(listing: AuthoredListing, kind: Int): AuthoredListing = AuthoredListing(
            authorPubkey = listing.authorPubkey,
            createdAt = listing.createdAt,
            dValue = listing.dValue,
            title = listing.title,
            price = listing.price,
            content = listing.content,
            summary = listing.summary,
            publishedAt = listing.publishedAt,
            status = listing.status?.token?.let { ListingStatusCodec.read(it, kind) },
            mimeType = listing.mimeType,
            topics = listing.topics,
            images = listing.images,
            expiration = listing.expiration,
            alt = listing.alt,
            nenyaVersion = listing.nenyaVersion,
            pubkeyRefs = listing.pubkeyRefs,
            fee = listing.fee,
            feeRecipient = listing.feeRecipient,
            license = listing.license,
            deliverBy = listing.deliverBy,
            extraTags = listing.extraTags,
        )
    }

