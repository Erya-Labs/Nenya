    /**
     * §5.2's `kind:30404`, §5.1's `kind:30402` and §5.1's `kind:30403`: each crossing's answer is the
     * answer `ListingWriter`'s own entry point gives for the same listing.
     *
     * The three are swept together because the body is one comparison, and each is called **by name**
     * in the `when` below rather than through a function reference, so the published function under
     * test is visible at the call site. The per-kind counts are asserted at the end, so a routing bug
     * that sent every call to one writer cannot pass: the three kinds would stop appearing.
     */
    @Test
    @JsName("the_three_listing_builders_answer_what_ListingWriter_answers")
    fun `the three listing builders answer what ListingWriter answers`() {
        val cases = ListingWriterFixtures.cases(LISTING_CASES)
        assertEquals(LISTING_CASES, cases.size, "the corpus is not the size this test is about")

        var built = 0
        var refused = 0
        val kindsBuilt = mutableSetOf<Int>()
        for (case in cases) {
            val crossed = JsBoundaryFixtures.crossed(case.listing)
            for (kind in LISTING_KINDS) {
                val what = "listing #${case.index} as kind $kind"
                val answer = when (kind) {
                    NenyaKind.REQUEST -> buildListingRequest(crossed)
                    NenyaKind.OFFER -> buildListingOffer(crossed)
                    else -> buildListingDraft(crossed)
                }
                // Through `answerOfCall`, because §5.1's closed `status` vocabulary refuses one of
                // §5.2's request tokens by **throwing** from `ListingStatusCodec.read`, before any
                // writer is reached. That is a refusal the boundary has to return, and comparing
                // only `ListingBuild` values would have let it escape unnoticed.
                val expected = JsBoundaryFixtures.answerOfCall {
                    JsBoundaryFixtures.answerOf(ListingWriterFixtures.build(kind, asKind(case.listing, kind)))
                }
                JsBoundaryFixtures.assertSameAnswer(answer, expected, what)
                if (expected.ok) {
                    built++
                    kindsBuilt += expected.event?.kind ?: fail("$what: a built answer with no event")
                } else {
                    refused++
                }
            }
        }

        // Non-vacuity: a corpus the writer refused everywhere, or accepted everywhere, would leave one
        // half of every comparison above unreachable.
        assertTrue(built > 100, "only $built of the ${cases.size * 3} crossings built an event")
        assertTrue(refused > 0, "no crossing was refused, so the refusal half of the equality is untested")
        assertEquals(
            LISTING_KINDS.toSet(),
            kindsBuilt,
            "the three entry points must emit §5.1's and §5.2's three kinds; a routing bug that sent " +
                "every call to one writer would show up here and nowhere else",
        )
    }

    /**
     * §5.1's two `status` refusals, each reached through the boundary and each named.
     *
     * The sweep above proves the two sides *agree* about refusals. This proves the refusals they agree
     * about are real §5.1 ones and names both reasons, so "they agree" cannot be satisfied by two sides
     * that both refuse everything for the same uninteresting reason. They are different rules reached
     * at different points, and the first is the one that caught a defect:
     *
     * - **One of §5.2's request tokens on an offer** is `STATUS_OUTSIDE_VOCABULARY`, raised by
     *   `ListingStatusCodec.read` **during the translation**, before `ListingWriter` is called. A JVM
     *   caller gets an exception; decision **P** says the boundary returns it, and it did not —
     *   `jsBuild`'s catch list had no arm for `ListingException` until this test was written.
     * - **A token §5.1 and §5.2 both lack** reads as `UNKNOWN` and is refused by the *writer* as
     *   `UNKNOWN_IS_NOT_EMITTABLE`, which is the path that already worked.
     *
     * The first token is derived from the difference between §5.2's and §5.1's own vocabularies rather
     * than typed, so a revision that moved a status between them cannot leave this control testing
     * nothing.
     */
    @Test
    @JsName("both_section_5_1_status_refusals_are_returned_as_values_on_both_sides")
    fun `both section 5 1 status refusals are returned as values on both sides`() {
        val requestOnly = ListingStatusCodec.vocabulary(NenyaKind.REQUEST) -
            ListingStatusCodec.vocabulary(NenyaKind.OFFER)
        val requestToken = requestOnly.firstNotNullOfOrNull { it.token }
            ?: fail("§5.2's request vocabulary no longer holds a status §5.1's offer vocabulary lacks")
        val invented = "part-exchanged"
        assertEquals(
            ListingStatus.UNKNOWN,
            ListingStatusCodec.read(invented, NenyaKind.OFFER),
            "this control needs a token neither §5.1 nor §5.2 names",
        )

        val base = ListingWriterFixtures.minimal(NenyaKind.OFFER)
        fun crossedWith(token: String): JsAuthoredListing = JsAuthoredListing(
            authorPubkey = base.authorPubkey,
            createdAtSeconds = JsBoundaryFixtures.decimal(base.createdAt),
            dValue = base.dValue,
            title = base.title,
            priceMsat = JsBoundaryFixtures.decimal(base.price.millisatoshis),
            statusToken = token,
            alt = base.alt,
        )
        fun libraryAnswerFor(token: String): JsBoundaryFixtures.Answer =
            JsBoundaryFixtures.answerOfCall {
                JsBoundaryFixtures.answerOf(
                    ListingWriter.offer(
                        AuthoredListing(
                            authorPubkey = base.authorPubkey,
                            createdAt = base.createdAt,
                            dValue = base.dValue,
                            title = base.title,
                            price = base.price,
                            status = ListingStatusCodec.read(token, NenyaKind.OFFER),
                            alt = base.alt,
                        ),
                    ),
                )
            }

        val outside = buildListingOffer(crossedWith(requestToken))
        JsBoundaryFixtures.assertSameAnswer(
            outside,
            libraryAnswerFor(requestToken),
            "an offer carrying §5.2's `$requestToken`",
        )
        assertFalse(outside.ok, "§5.1's offer vocabulary is closed")
        assertEquals(
            "STATUS_OUTSIDE_VOCABULARY",
            outside.reason,
            "the refusal must be §5.1's own, raised during the translation and **returned** rather " +
                "than thrown past the boundary",
        )
        assertEquals("ListingRejection", outside.reasonVocabulary, "and from §5's vocabulary")

        val unknown = buildListingOffer(crossedWith(invented))
        JsBoundaryFixtures.assertSameAnswer(
            unknown,
            libraryAnswerFor(invented),
            "an offer carrying the invented `$invented`",
        )
        assertFalse(unknown.ok, "§5.2 makes `unknown` a treatment rather than a token")
        assertEquals(
            "UNKNOWN_IS_NOT_EMITTABLE",
            unknown.reason,
            "this one is the writer's refusal, which is a different rule at a different point",
        )
        assertNotEquals(
            outside.reason,
            unknown.reason,
            "the two rules must be told apart; one reason for both would hide which fired",
        )
    }

