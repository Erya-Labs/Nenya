    @Test
    @JsName("decodeListing_reports_what_Listing_decode_reports")
    fun `decodeListing reports what Listing decode reports`() {
        var compared = 0
        for (case in ListingWriterFixtures.cases(DECODE_CASES)) {
            val event = when (val build = ListingWriterFixtures.build(case.kind, case.listing)) {
                is ListingBuild.Built -> build.event
                is ListingBuild.Refused -> continue
            }
            val what = "listing #${case.index} on kind ${case.kind}"
            val expected = Listing.decode(CheckedEvent.checkEventId(EventId.of(event).toHex(), event))
            val answer = decodeListing(JsBoundaryFixtures.json(event))

            assertTrue(answer.ok, "$what: the crossing refused what the library decoded: ${answer.reason}")
            assertEquals("listing", answer.kind, "$what: `kind` must discriminate with `ok`")
            val crossed = answer.listing ?: fail("$what: an ok answer with no listing")
            JsBoundaryFixtures.assertSameFields(JsBoundaryFixtures.listingFields(crossed, expected), what)
            assertNull(answer.reason, "$what: an ok answer must name no reason")
            compared++
        }
        assertTrue(compared > 100, "only $compared listings reached the decode comparison")
    }

