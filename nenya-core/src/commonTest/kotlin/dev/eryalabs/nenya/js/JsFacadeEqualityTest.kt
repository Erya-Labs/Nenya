    /** Every corpus case of [shape], with a floor so a filter that matched nothing cannot pass. */
    private fun forEachShape(
        shape: RumorWriterFixtures.Shape,
        body: (RumorWriterFixtures.Case) -> Unit,
    ) {
        val cases = RUMORS.filter { it.shape == shape }
        assertTrue(
            cases.size >= RUMOR_CASES / RumorWriterFixtures.Shape.entries.size,
            "${cases.size} case(s) of $shape is not the corpus this test is about",
        )
        for (case in cases) body(case)
    }

    private fun requireOrder(case: RumorWriterFixtures.Case): OrderId =
        case.order ?: fail("$case must carry §7.4's order id")

    private fun requireOrderHex(case: RumorWriterFixtures.Case): String = requireOrder(case).toHex()

    private fun requireItem(case: RumorWriterFixtures.Case): ItemRef =
        case.item ?: fail("$case must carry §5.3's item")

    private fun requireItemCoordinate(case: RumorWriterFixtures.Case): String =
