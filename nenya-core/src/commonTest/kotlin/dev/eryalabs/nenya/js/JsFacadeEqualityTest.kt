    /**
     * Every refusal the two decoders can report comes from the library, named the way the library
     * names it.
     *
     * The positive sweeps above cannot reach these: a corpus of events this library built decodes by
     * construction. Each case here is hostile input of a different shape and each lands on a different
     * arm of the decoders' catch ladders — which is what proves the arms are wired to the right
     * vocabulary rather than all answering the same thing.
     */
    @Test
    @JsName("both_decoders_report_the_librarys_own_refusal_for_hostile_input")
    fun `both decoders report the library's own refusal for hostile input`() {
        val listing = ListingWriterFixtures.built(
            ListingWriterFixtures.build(NenyaKind.OFFER, ListingWriterFixtures.minimal(NenyaKind.OFFER)),
            "the minimal offer",
        )
        val listingJson = JsBoundaryFixtures.json(listing)
        // A second event, so the id substituted below is one this repository computed rather than a
        // hex string somebody typed out (the Definition of done's rule on encoded values).
        val other = ListingWriterFixtures.built(
            ListingWriterFixtures.build(
                NenyaKind.OFFER,
                ListingWriterFixtures.minimal(NenyaKind.OFFER, index = 1),
            ),
            "a second offer",
        )
        val mismatched = listingJson.replace(EventId.of(listing).toHex(), EventId.of(other).toHex())
        assertNotEquals(listingJson, mismatched, "the id-mismatch case must actually differ")

        val bidEvent = WireEvent(
            TagFixtures.pubkeyFor(0),
            BidFixtures.CREATED_AT,
            NenyaKind.PUBLIC_BID,
            BidFixtures.minimalBid(),
            "",
        )
        val bidJson = JsBoundaryFixtures.json(bidEvent)

        val vocabularies = mutableSetOf<String>()

        // §4.3's JSON rules, before any §5 or §6 rule runs.
        for (hostile in listOf("", "not an event", "{\"id\":")) {
            val answer = decodeListing(hostile)
            assertFalse(answer.ok, "`$hostile` is not an event object")
            assertEquals(
                "JsonRejection",
                answer.reasonVocabulary,
                "§4.3's JSON rules refuse this one, and the crossing must say so",
            )
            vocabularies += "JsonRejection"
        }

        // §4.1's id check, which the decoder cannot be reached without.
        val idAnswer = decodeListing(mismatched)
        assertFalse(idAnswer.ok, "an event whose id is not the hash of its own fields must be refused")
        assertEquals("WireRejection", idAnswer.reasonVocabulary, "§4.1's id check owns this refusal")
        assertEquals("ID_MISMATCH", idAnswer.reason, "and names the rule it broke")
        vocabularies += "WireRejection"

        // §6's bid fed to §5's decoder, and the reverse: each decoder's own kind check.
        val notAListing = decodeListing(bidJson)
        assertFalse(notAListing.ok, "a kind:1111 bid is not a listing")
        assertEquals("ListingRejection", notAListing.reasonVocabulary, "§5's decoder owns this refusal")
        vocabularies += "ListingRejection"

        val notABid = decodeBid(listingJson)
        assertFalse(notABid.ok, "a kind:30402 offer is not a bid")
        assertEquals("BidRejection", notABid.reasonVocabulary, "§6's decoder owns this refusal")
        vocabularies += "BidRejection"

        // The two positive controls, so "everything is refused" cannot satisfy this test.
        assertTrue(decodeListing(listingJson).ok, "the minimal offer must still decode")
        assertTrue(decodeBid(bidJson).ok, "the minimal bid must still decode")

        assertEquals(
            setOf("JsonRejection", "WireRejection", "ListingRejection", "BidRejection"),
            vocabularies,
            "four different arms of the two decoders' catch ladders must have been reached",
        )
        assertFalse(
            JsCrossing.VOCABULARY in vocabularies,
            "not one of these refusals may come from the crossing's own vocabulary: a decoder that " +
                "answered `${JsCrossing.VOCABULARY}` would be deciding a §4, §5 or §6 question itself",
        )
    }

