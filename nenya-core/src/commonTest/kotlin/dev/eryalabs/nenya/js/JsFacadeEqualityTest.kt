    /**
     * A `status` token §11.1 has no rule for reaches the **writer's** refusal, not the crossing's.
     *
     * `OrderStatusCodec.read` never throws — §11.1 makes an unrecognised status a fact about the
     * counterparty rather than a malformed input — so the crossing hands `UNKNOWN` to the writer and
     * the writer refuses it. That is the discipline under test: the crossing restates no vocabulary,
     * and the assertion on [JsCrossing.VOCABULARY] is what says so.
     */
    @Test
    @JsName("an_unknown_status_token_reaches_the_writers_own_refusal_on_both_sides")
    fun `an unknown status token reaches the writer's own refusal on both sides`() {
        val case = RUMORS.first { it.shape == RumorWriterFixtures.Shape.ORDER_UPDATE }
        val invented = "part-exchanged"
        assertEquals(
            OrderState.UNKNOWN,
            OrderStatusCodec.read(invented),
            "this control needs a token §11.1 has no rule for",
        )

        val answer = buildStatusUpdate(
            envelope = JsBoundaryFixtures.crossed(case.envelope),
            orderIdHex = requireOrderHex(case),
            statusToken = invented,
            itemCoordinate = case.item?.coordinate?.toTagValue(),
            terms = case.terms?.let { JsBoundaryFixtures.crossed(it) },
            feeRecipient = case.feeRecipient,
        )
        val expected = JsBoundaryFixtures.answerOf(
            RumorWriter.statusUpdate(
                case.envelope,
                requireOrder(case),
                OrderState.UNKNOWN,
                case.item,
                case.terms,
                case.feeRecipient,
            ),
        )

        JsBoundaryFixtures.assertSameAnswer(answer, expected, "a status update carrying `$invented`")
        assertFalse(answer.ok, "§11.1's `unknown` is a treatment rather than a token")
        assertNotEquals(
            JsCrossing.VOCABULARY,
            answer.reasonVocabulary,
            "the refusal must come from the writer, never from the crossing's own vocabulary",
        )
    }

